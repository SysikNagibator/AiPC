def current_lang() -> str:
    try:
        from .config import load_config

        cfg = load_config()
        # Канонический ключ language побеждает, если он не дефолтный;
        # иначе — старый lang (миграция без потери русской настройки).
        lang = str(cfg.get("language", "en") or "en")
        if lang.lower() == "en":
            lang = str(cfg.get("lang", "en") or "en")
        lang = lang.lower()
    except Exception:
        lang = "en"
    return lang if lang in ("en", "ru") else "en"


def t(key: str, fallback: str = "", lang: str | None = None) -> str:
    """Строка по ключу для текущего языка. Fallback -> ключ -> пусто.
    lang задаёт язык явно (для рендера); без него — из конфига."""
    l = (lang or current_lang()).lower()
    table = RU if l == "ru" else EN
    return table.get(key) or EN.get(key) or fallback or key
